// Client-side JS for Single Window Application Submission Form

function autofillApplication(name, pan, type, survey, load) {
  document.getElementById('orgNameInput').value = name;
  document.getElementById('orgPanInput').value = pan;
  document.getElementById('projectTypeInput').value = type;
  document.getElementById('surveyNoInput').value = survey;
  document.getElementById('loadInput').value = load;
}

async function handleApplicationSubmit(e) {
  e.preventDefault();

  const orgName = document.getElementById('orgNameInput').value.trim();
  const orgPan = document.getElementById('orgPanInput').value.trim().toUpperCase();
  const projectType = document.getElementById('projectTypeInput').value;
  const surveyNo = document.getElementById('surveyNoInput').value.trim();
  const loadKw = document.getElementById('loadInput').value.trim();
  const location = document.getElementById('locationInput').value.trim();

  const submitBtn = document.getElementById('submitBtn');
  submitBtn.disabled = true;
  submitBtn.innerText = 'Submitting & Dispatching...';

  try {
    const res = await fetch('http://localhost:5000/api/interop/submit-application', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        organizationName: orgName,
        organizationPan: orgPan,
        projectType: projectType,
        surveyNumber: surveyNo,
        requestedLoadKw: loadKw,
        location: location
      })
    });

    const data = await res.json();

    if (res.ok && data.success) {
      document.getElementById('submissionResult').style.display = 'block';
      document.getElementById('ackAppId').innerText = data.applicationId;
      document.getElementById('ackPan').innerText = orgPan;
      document.getElementById('appStatusBadge').innerText = data.status;

      // Render the parallel verifications generated by the interop orchestrator
      const container = document.getElementById('dependencyChecklist');
      container.innerHTML = '';

      if (data.pendingVerifications && data.pendingVerifications.length > 0) {
        data.pendingVerifications.forEach(item => {
          const row = document.createElement('div');
          row.className = 'list-row';
          row.innerHTML = `
            <div style="display: flex; align-items: center; gap: 10px;">
              <span class="tag tag-blue">${item.department}</span>
              <span style="font-weight: 600;">${item.type}</span>
            </div>
            <div style="display: flex; align-items: center; gap: 8px;">
              <span class="tag tag-amber">PARALLEL DISPATCH</span>
              <span style="font-size: 11px; color: var(--text-muted);">${item.required ? 'Mandatory Prerequisite' : 'Optional'}</span>
            </div>
          `;
          container.appendChild(row);
        });
      }

      document.getElementById('rawSubmitJson').innerText = JSON.stringify(data, null, 2);

      // Scroll smoothly to results
      document.getElementById('submissionResult').scrollIntoView({ behavior: 'smooth' });
    } else {
      alert(`Submission Failed: ${data.message || 'Error occurred'}`);
    }
  } catch (err) {
    alert('Failed to connect to the Interoperability server on port 5000.');
  } finally {
    submitBtn.disabled = false;
    submitBtn.innerText = 'Submit Application ➔';
  }
}
